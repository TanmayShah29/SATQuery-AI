"""Run the Phase 1 probe queries through the regex AgentRouter and write PROBES.md.

The probes motivate the project; they are NOT the test set and are never trained on.
Run from ml/router_ft:  uv run python run_probes.py
"""

import json
from pathlib import Path

from routers.regex_router import route

ROOT = Path(__file__).resolve().parents[2]
PROBES = ROOT / "data" / "router_ft" / "probes.jsonl"
OUT_DIR = ROOT / "results" / "router_ft" / "probes_regex"
DOC = ROOT / "docs" / "router-ft" / "PROBES.md"

FIELDS = ("intent", "secondary_intents", "entities", "temporal", "cloud_piercing_required")
SHORT = {"intent": "intent", "secondary_intents": "secondary", "entities": "entities",
         "temporal": "temporal", "cloud_piercing_required": "cloud"}


def _field_ok(field, gold, pred):
    if field in ("secondary_intents", "entities"):
        return set(gold[field]) == set(pred[field])
    return gold[field] == pred[field]


def _fmt(v):
    return "∅" if v in (None, []) else (", ".join(v) if isinstance(v, list) else str(v))


def main():
    probes = [json.loads(line) for line in PROBES.read_text().splitlines() if line.strip()]
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    with open(OUT_DIR / "predictions.jsonl", "w") as f:
        for p in probes:
            pred = route(p["query"], p["hints"])
            ok = {fld: _field_ok(fld, p["label"], pred) for fld in FIELDS}
            rows.append((p, pred, ok))
            f.write(json.dumps({"id": p["id"], "query": p["query"], "hints": p["hints"],
                                "gold": p["label"], "pred": pred, "field_correct": ok}, ensure_ascii=False) + "\n")

    n = len(rows)
    per_field = {fld: sum(r[2][fld] for r in rows) for fld in FIELDS}
    all_ok = sum(all(r[2].values()) for r in rows)

    lines = [
        "# Probe queries: where the regex router fails",
        "",
        "Generated by `ml/router_ft/run_probes.py` from `data/router_ft/probes.jsonl`;",
        "raw predictions in `results/router_ft/probes_regex/predictions.jsonl`.",
        "",
        "**What this is:** 20 queries written to hit known weak spots (paraphrase, negation,",
        "typos/Hinglish, compound requests, keyword traps), plus a few plain ones. Gold labels",
        "follow [GUIDELINES.md](GUIDELINES.md). **What it is not:** a measurement. The probes",
        "were chosen to expose failures, so these rates say nothing about real traffic. The",
        "frozen, hand-written test set (Phase 2) is the measurement.",
        "",
        "## Summary",
        "",
        f"Fully correct (all 5 fields): **{all_ok} / {n}**",
        "",
        "| Field | Correct |",
        "|---|---|",
    ]
    lines += [f"| {SHORT[fld]} | {per_field[fld]} / {n} |" for fld in FIELDS]
    lines += ["", "## Per probe", "",
              "✗ marks a wrong field; the regex value is shown, with gold after the arrow.", "",
              "| # | Slice | Query | Hints | intent | secondary | entities | temporal | cloud |",
              "|---|---|---|---|---|---|---|---|---|"]
    for p, pred, ok in rows:
        hints = "bitemporal pair" if p["hints"]["has_bitemporal_pair"] else "default"
        cells = []
        for fld in FIELDS:
            cells.append(f"✓ {_fmt(pred[fld])}" if ok[fld] else f"✗ {_fmt(pred[fld])} → {_fmt(p['label'][fld])}")
        lines.append(f"| {p['id'][-2:]} | {', '.join(p['slices'])} | {p['query']} | {hints} | " + " | ".join(cells) + " |")
    DOC.write_text("\n".join(lines) + "\n")
    print(f"fully correct {all_ok}/{n}; " + ", ".join(f"{SHORT[f]} {per_field[f]}/{n}" for f in FIELDS))


if __name__ == "__main__":
    main()
